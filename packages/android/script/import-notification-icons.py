"""Import only missing notification vectors from a local, pinned Termux:API checkout.

Usage: python3 script/import-notification-icons.py /path/to/termux-api
No network access is required by the APK or the build.
"""
import hashlib
import io
from pathlib import Path
import re
import subprocess
import sys
import tarfile

REV = '6c8eaa223bcc387e6b28146d340acb20712aa3e7'  # v0.53.0
DIGEST = '764a50300a9bb3a1ec2713110fb8957c63ecdfa8bcb9d1c617ea9275c77df81c'
BASE = 'app/src/main/res/drawable'
DEST = Path(__file__).resolve().parents[1] / 'third_party/notification-icons/res'
EXISTING = {'done', 'event_note', 'warning'}


def main(repo):
    # Read committed blobs, not possibly modified working-tree resources.
    archive = subprocess.check_output(['git', '-C', repo, 'archive', REV, BASE])
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        icons = {m[1]: tar.extractfile(item).read() for item in tar if item.isfile()
                 and (m := re.fullmatch(BASE + r'/ic_([a-z0-9_]+)_black_24dp\.xml', item.name))}
    names = sorted(icons)
    digest = hashlib.sha256(('\n'.join(names) + '\n').encode()).hexdigest()
    if len(names) != 959 or digest != DIGEST or not EXISTING <= icons.keys() or 'server' in icons:
        raise ValueError(f'Unexpected upstream catalog: {len(names)} names, sha256={digest}')
    drawables = DEST / 'drawable'; drawables.mkdir(parents=True, exist_ok=True)
    (DEST / 'values').mkdir(exist_ok=True)
    items = []
    for name in names:
        resource = f'ic_{name}'
        if name not in EXISTING:
            resource += '_black_24dp'
            (drawables / f'{resource}.xml').write_bytes(icons[name])
        items.append(f'        <item>@drawable/{resource}</item>')
    # AAPT links these references; do not expose arbitrary drawable lookups to MCP callers.
    (DEST / 'values/notification_icon_catalog.xml').write_text('\n'.join([
        '<!-- Generated by script/import-notification-icons.py; server is the OpenCode-only entry. -->',
        '<resources>', '    <array name="notification_small_icons">',
        '        <item>@drawable/ic_server</item>', *items, '    </array>', '</resources>', '']), encoding='utf-8')
    print(f'upstream={len(names)} existing={len(EXISTING)} imported={len(names)-len(EXISTING)} extra=server catalog={len(items)+1}')


if __name__ == '__main__':
    main(sys.argv[1])
